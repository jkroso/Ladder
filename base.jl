# The files that almost every file of Ladder needs, as one file: the look of
# the page (look.jl), a line laid out (flow.jl), the document (buffer.jl), what
# a window holds (editor_type.jl), the faces of the text (faces.jl), rich text
# and tables (rich.jl), what the page asks of a block (blocks.jl), the lines
# and the shapes that a block draws (strokes.jl), the functions that several
# files give methods to (shared.jl), what a part of a page asks of its window
# (host.jl), the parts of a folder's page (folder_page.jl) and what the window
# asks of a folder or a file (views.jl). A file gets every name that they
# export with one line:
#
#     @use "./base" exports...
#
# This file defines nothing. It exports each name that one of those files
# exports, so a new name in one of them needs no change here. A new file of
# this kind needs a line here, and its name in the list under the lines.
# main.jl loads those files itself, before any file that loads this one.

@use "./look" => LowLook exports...
@use "./flow" => LowFlow exports...
@use "./buffer" => LowBuffer exports...
@use "./editor_type" => LowEditorType exports...
@use "./faces" => LowFaces exports...
@use "./rich" => LowRich exports...
@use "./blocks" => LowBlocks exports...
@use "./strokes" => LowStrokes exports...
@use "./shared" => LowShared exports...
@use "./host" => LowHost exports...
@use "./folder_page" => LowFolderPage exports...
@use "./views" => LowViews exports...

for low in (LowLook, LowFlow, LowBuffer, LowEditorType, LowFaces, LowRich, LowBlocks, LowStrokes, LowShared, LowHost, LowFolderPage, LowViews), name in names(low)
  name === nameof(low) || Core.eval(@__MODULE__, Expr(:export, name))
end
